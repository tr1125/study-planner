"""Study Planner on the Claude Agent SDK: Claude Code runs the harness, we configure it.

Lines tagged `# replaces: <part>` stand in for API/harness/<part>.py.
"""
from __future__ import annotations

import asyncio
import json
from pathlib import Path

from claude_agent_sdk import (
    AssistantMessage,
    ClaudeAgentOptions,
    ClaudeSDKClient,
    ResultMessage,
    ToolUseBlock,
)

from SDK.tools import SERVER_NAME, build_server
from shared.prompts import EFFORT, MODEL, system_prompt
from shared.store import weekday
from shared.tools import Domain

# replaces: compaction -- nothing to write: Claude Code auto-compacts near the context limit.
# replaces: caching -- nothing to write: Claude Code places cache_control breakpoints itself.

CLAUDE_MD = """# Study Planner: project memory
Generated by SDK/agent.py from memory.json at the start of every session.

planner_date: {today} ({weekday})

## Saved memory (active facts; use recall for retired ones)
{facts}
"""


def log(msg: str) -> None:
    print(f"[SDK/agent.py] {msg}", flush=True)


class StudyAgentSDK:
    def __init__(self, data_dir: Path, today: str, session: str = "s1", resume: bool = False,
                 client_factory=ClaudeSDKClient, fetch=None, run_tag: str | None = None):
        self.data_dir = Path(data_dir)
        self.session = session
        self.domain = Domain(self.data_dir, today, fetch=fetch)
        self.workspace = self.data_dir / "sdk_workspace"
        self.workspace.mkdir(parents=True, exist_ok=True)
        (self.workspace / "CLAUDE.md").write_text(CLAUDE_MD.format(  # replaces: memory, context
            today=today, weekday=weekday(today), facts=self.domain.memory.to_markdown()),  # replaces: memory, context
            encoding="utf-8")
        self.sessions_file = self.data_dir / "sdk_sessions.json"
        resume_id = self._saved_sessions().get(session) if resume else None  # replaces: history
        server, tool_names = build_server(self.domain)
        self.options = ClaudeAgentOptions(
            system_prompt=system_prompt(run_tag),   # our own prompt instead of Claude Code's default
            model=MODEL,
            effort=EFFORT,
            mcp_servers={SERVER_NAME: server},  # replaces: tools
            strict_mcp_config=True,                 # ignore any other MCP config on this machine
            tools=[],                               # no built-in tools (Bash, Read, Web...) at all
            allowed_tools=tool_names,  # replaces: tools
            permission_mode="dontAsk",              # anything not in allowed_tools is denied, never prompted
            setting_sources=["project"],  # replaces: memory
            cwd=str(self.workspace),  # replaces: memory
            resume=resume_id,  # replaces: history
            max_turns=15,  # replaces: loop
        )
        self._prev_usage: dict = {}
        self._prev_cost = 0.0
        self._loop = asyncio.Runner()   # one event loop for the whole session (the client is async)
        self.client = client_factory(options=self.options)
        self._loop.run(self.client.connect())  # replaces: loop
        log(f"connected: session={session} resume={resume_id or 'no'} model={MODEL} effort={EFFORT} "
            f"tools={len(tool_names)}")

    def _saved_sessions(self) -> dict:
        if self.sessions_file.exists():
            return json.loads(self.sessions_file.read_text(encoding="utf-8"))
        return {}

    def _save_session_id(self, session_id: str) -> None:
        sessions = self._saved_sessions()
        sessions[self.session] = session_id  # replaces: history
        self.sessions_file.write_text(json.dumps(sessions, indent=1), encoding="utf-8")  # replaces: history

    def run_turn(self, text: str) -> dict:
        return self._loop.run(self._turn(text))

    async def _turn(self, text: str) -> dict:
        await self.client.query(text)  # replaces: loop
        tools: list[str] = []
        message_ids: set[str] = set()
        result: ResultMessage | None = None
        async for msg in self.client.receive_response():  # replaces: loop
            if isinstance(msg, AssistantMessage):
                message_ids.add(msg.message_id or str(id(msg)))  # replaces: tokens
                for block in msg.content:
                    if isinstance(block, ToolUseBlock):
                        tools.append(block.name.removeprefix(f"mcp__{SERVER_NAME}__"))
            elif isinstance(msg, ResultMessage):
                result = msg
        if result is None:
            raise RuntimeError("Claude Code ended the turn without a ResultMessage")
        self._save_session_id(result.session_id)
        tokens, by_model, cost = self._turn_usage(result)
        log(f"result: subtype={result.subtype} turns={result.num_turns} tokens={tokens} "
            f"cost=${cost:.5f} models={list(by_model)}")
        return {
            "reply": result.result or "",
            "tokens": tokens,
            "model_calls": len(message_ids),
            "tools": tools,
            "cost_usd": round(cost, 6),
            "sdk": {"num_turns": result.num_turns, "duration_api_ms": result.duration_api_ms,
                    "subtype": result.subtype, "main_loop_usage": result.usage, "tokens_by_model": by_model},
        }

    def _turn_usage(self, result: ResultMessage) -> tuple[dict, dict, float]:
        """ResultMessage.usage covers only the main model for this turn, while model_usage and
        total_cost_usd are cumulative for the session and include Claude Code's own side calls
        (e.g. a small Haiku request). Per-turn numbers = difference from the previous turn."""
        cumulative = {  # replaces: tokens
            model: {"input": u.get("inputTokens", 0), "cache_read": u.get("cacheReadInputTokens", 0),  # replaces: tokens
                    "cache_write": u.get("cacheCreationInputTokens", 0), "output": u.get("outputTokens", 0)}  # replaces: tokens
            for model, u in (result.model_usage or {}).items()  # replaces: tokens
        }
        by_model = {}
        for model, now in cumulative.items():
            before = self._prev_usage.get(model, {})
            delta = {k: v - before.get(k, 0) for k, v in now.items()}  # replaces: tokens
            if any(delta.values()):
                by_model[model] = delta
        tokens = {k: sum(d[k] for d in by_model.values()) for k in ("input", "cache_read", "cache_write", "output")}  # replaces: tokens
        cost = (result.total_cost_usd or 0.0) - self._prev_cost  # replaces: tokens
        self._prev_usage, self._prev_cost = cumulative, result.total_cost_usd or 0.0
        return tokens, by_model, cost

    def close(self) -> None:
        try:
            self._loop.run(self.client.disconnect())
        finally:
            self._loop.close()
        log("disconnected")
